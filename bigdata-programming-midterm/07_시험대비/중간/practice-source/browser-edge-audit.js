async (page) => {
  const checks=[],check=(v,t)=>{if(!v)throw Error(t);checks.push(t);};
  const rec=()=>page.evaluate(()=>JSON.parse(localStorage.getItem(window.BIGDATA_PRACTICE.key)));
  const q1=await page.evaluate(()=>window.BIGDATA_PRACTICE.bank.find(q=>q.id==='BC01'));
  await page.locator('[data-type="code"]').click();
  await page.locator('#retryOne').click();
  await page.locator('#star').click();
  for(let i=0;i<q1.blanks.length;i++)await page.locator('.blank').nth(i).fill(q1.blanks[i].answer+(i===0?' ':''));
  await page.locator('#submit').click();
  check((await page.locator('.result').innerText()).startsWith('오답'),'code-space-strict');
  await page.locator('[data-filter="wrong"]').click();
  check(await page.locator('#retryBar').isHidden(),'wrong-first-click-collapsed');
  const old=(await rec()).answers.BC01;
  await page.locator('[data-filter="wrong"]').click();
  check(await page.locator('#retryBar').isVisible(),'wrong-second-click-expanded');
  await page.locator('#startRetry').click();
  check(await page.locator('.result').count()===0,'retry-no-solution');
  await page.locator('.blank').first().fill('draft');
  await page.reload();
  check(await page.locator('.blank').first().inputValue()==='draft','retry-draft-reload');
  check(await page.locator('#retryBar').isHidden(),'reload-retry-controls-collapsed');
  await page.locator('[data-filter="wrong"]').click();
  await page.locator('#endRetry').click();
  check(JSON.stringify((await rec()).answers.BC01)===JSON.stringify(old),'ungraded-retry-restores-old-answer');
  await page.locator('[data-filter="wrong"]').click();
  await page.locator('[data-filter="wrong"]').click();
  await page.locator('#startRetry').click();
  for(let i=0;i<q1.blanks.length;i++)await page.locator('.blank').nth(i).fill(q1.blanks[i].answer);
  await page.locator('#submit').click();
  check((await rec()).answers.BC01.correct,'retry-correct-saved');
  await page.locator('#endRetry').click();
  await page.locator('[data-filter="wrong"]').click();
  check(await page.locator('.empty').count()===1,'resolved-excluded-from-wrong');
  await page.locator('[data-filter="all"]').click();
  await page.locator('[data-type="short"]').click();
  await page.locator('#retryOne').click();
  await page.locator('#short').fill('Syntax Error');
  await page.locator('#submit').click();
  check((await rec()).answers.BS01.correct,'concept-whitespace-allowed');
  await page.locator('#retryOne').click();
  await page.locator('#short').fill('syntaxerror');
  await page.locator('#submit').click();
  check(!(await rec()).answers.BS01.correct,'concept-case-strict');
  const before=(await rec()).answers.BS01;
  page.once('dialog',d=>d.dismiss());
  await page.locator('#resetAll').click();
  check(JSON.stringify((await rec()).answers.BS01)===JSON.stringify(before),'reset-cancel-preserved');
  page.once('dialog',d=>d.accept());
  await page.locator('#resetAll').click();
  let saved=await rec();
  check(!Object.keys(saved.answers).some(id=>id.startsWith('BS')),'reset-only-current-type');
  check(saved.answers.BC01.correct&&saved.stars.BC01,'reset-keeps-other-type-and-star');
  await page.reload();
  check(!(await rec()).answers.BS01,'reset-persists');
  await page.locator('#short').focus();
  await page.keyboard.type('1,.');
  check(await page.locator('#short').inputValue()==='1,.','input-shortcuts-not-hijacked');
  await page.locator('[data-type="mc"]').click();
  await page.locator('#retryOne').click();
  await page.locator('h1').click();
  const mc=await page.evaluate(()=>window.BIGDATA_PRACTICE.bank.find(q=>q.id==='BM01'));
  await page.keyboard.press(String(mc.correct+1));
  check((await rec()).answers.BM01.correct,'mc-number-shortcut');
  await page.locator('#retryOne').click();
  await page.locator(`[data-choice="${(mc.correct+1)%mc.options.length}"]`).click();
  check(!(await rec()).answers.BM01.correct,'mc-wrong-grading');
  check(await page.locator('.opt-exp').count()===mc.options.length,'mc-wrong-all-explanations');
  await page.locator('[data-type="code"]').click();
  await page.locator('#retryOne').click();
  await page.locator('#card').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:'output/playwright/bigdata-practice-mobile.png'});
  for(const [width,height] of [[320,640],[375,667],[390,500],[768,1024],[1440,900]]){
    await page.setViewportSize({width,height});
    const v=await page.evaluate(()=>({w:document.documentElement.clientWidth,sw:document.documentElement.scrollWidth,h:innerHeight,sh:document.documentElement.scrollHeight,b:document.querySelector('footer').getBoundingClientRect().bottom}));
    check(v.w===v.sw&&v.sh<=v.h+1&&v.b<=v.h+1,`viewport-${width}x${height}`);
  }
  await page.screenshot({path:'output/playwright/bigdata-practice-desktop.png'});
  const report={passed:checks.length,checks};
  await page.evaluate(value=>window.__bigdataEdgeReport=value,report);
  return report;
}
